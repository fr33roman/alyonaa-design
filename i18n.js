let AD_LANG = "ru";
window.AD_T = (key) => (AD_I18N[AD_LANG] && AD_I18N[AD_LANG][key]) || AD_I18N.ru[key] || key;

function adApplyLang(lang) {
  if (!AD_I18N[lang]) lang = "ru";
  AD_LANG = lang;
  const dict = AD_I18N[lang];
  document.documentElement.lang = lang;

  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const val = dict[el.getAttribute("data-i18n")];
    if (val == null) return;
    if (/<[a-z][\s\S]*>/i.test(val)) el.innerHTML = val;
    else el.textContent = val;
  });

  document.title = dict["meta.title"];
  const md = document.querySelector('meta[name="description"]');
  if (md) md.setAttribute("content", dict["meta.desc"]);

  document.querySelectorAll(".lang-sw button").forEach((b) =>
    b.classList.toggle("on", b.getAttribute("data-lang") === lang)
  );

  /* мобильные табы тарифов собираются из таблицы — пересобираем на новом языке */
  if (typeof window.buildTariffTabs === "function") window.buildTariffTabs();

  try { localStorage.setItem("ad_lang", lang); } catch (_) {}
}

document.addEventListener("DOMContentLoaded", () => {
  let saved = null;
  try { saved = localStorage.getItem("ad_lang"); } catch (_) {}
  const browser = (navigator.language || "ru").slice(0, 2).toLowerCase();
  adApplyLang(saved || (browser === "ru" ? "ru" : "en"));

  document.querySelectorAll(".lang-sw button").forEach((b) =>
    b.addEventListener("click", () => adApplyLang(b.getAttribute("data-lang")))
  );
});
